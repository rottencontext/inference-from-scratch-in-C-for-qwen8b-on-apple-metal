#!/usr/bin/env python3
"""Generate unicode_tables.h for qwen3.c.

The tokenizer needs two pieces of Unicode data that are too big to type by hand:

  1. Which code points are letters (\\p{L}) and numbers (\\p{N}).  The Qwen
     pre-tokenizer regex is written in terms of these two classes.
  2. The data for NFC normalization (canonical decompositions, combining
     classes, and composition pairs).  The Qwen tokenizer normalizes text to
     NFC before doing anything else.

Everything comes from Python's built-in `unicodedata`, so this script has no
dependencies.  Run:  python3 tools/gen_unicode_tables.py > unicode_tables.h
"""
import sys
import unicodedata

MAX_CP = 0x110000


def ranges(pred):
    """Collapse the set {cp : pred(cp)} into sorted inclusive [lo, hi] ranges."""
    out, start = [], None
    for cp in range(MAX_CP):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX_CP - 1))
    return out


def is_hangul_syllable(cp):
    return 0xAC00 <= cp <= 0xD7A3


def main():
    cat = [unicodedata.category(chr(cp)) for cp in range(MAX_CP)]
    letters = ranges(lambda cp: cat[cp][0] == "L")
    numbers = ranges(lambda cp: cat[cp][0] == "N")

    # Canonical combining class, as (lo, hi, ccc) runs of equal non-zero class.
    ccc = [unicodedata.combining(chr(cp)) for cp in range(MAX_CP)]
    ccc_runs, start = [], None
    for cp in range(MAX_CP + 1):
        cur = ccc[cp] if cp < MAX_CP else 0
        if start is not None and (cur != ccc[start]):
            ccc_runs.append((start, cp - 1, ccc[start]))
            start = None
        if start is None and cur != 0:
            start = cp

    # Full canonical decomposition (NFD) of every code point that has one.
    # Hangul syllables are left out: they decompose by arithmetic.
    decomp = []
    for cp in range(MAX_CP):
        if is_hangul_syllable(cp) or 0xD800 <= cp <= 0xDFFF:
            continue
        d = unicodedata.normalize("NFD", chr(cp))
        if d != chr(cp):
            decomp.append((cp, [ord(c) for c in d]))
    max_len = max(len(d) for _, d in decomp)
    assert max_len <= 4, max_len

    # Composition pairs: (first, second) -> composite.  A pair qualifies when the
    # composite's own one-step canonical decomposition is exactly that pair and
    # NFC really does compose it (this drops the "composition exclusions").
    compose = []
    for cp in range(MAX_CP):
        if is_hangul_syllable(cp):
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        if len(parts) != 2:
            continue
        if unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
            compose.append((parts[0], parts[1], cp))
    compose.sort()

    w = sys.stdout.write
    w("/* unicode_tables.h -- GENERATED by tools/gen_unicode_tables.py. Do not edit.\n")
    w(" * Unicode version: %s (from Python %s unicodedata)\n */\n" % (unicodedata.unidata_version, sys.version.split()[0]))
    w("#ifndef UNICODE_TABLES_H\n#define UNICODE_TABLES_H\n#include <stdint.h>\n\n")

    def emit_ranges(name, rs):
        w("/* %d inclusive ranges */\n" % len(rs))
        w("static const uint32_t %s[][2] = {\n" % name)
        for i in range(0, len(rs), 6):
            w("  " + " ".join("{0x%X,0x%X}," % r for r in rs[i:i + 6]) + "\n")
        w("};\n#define %s_N %d\n\n" % (name, len(rs)))

    emit_ranges("UNI_LETTER", letters)
    emit_ranges("UNI_NUMBER", numbers)

    w("/* canonical combining class: {first, last, class}, non-zero classes only */\n")
    w("static const uint32_t UNI_CCC[][3] = {\n")
    for i in range(0, len(ccc_runs), 5):
        w("  " + " ".join("{0x%X,0x%X,%d}," % r for r in ccc_runs[i:i + 5]) + "\n")
    w("};\n#define UNI_CCC_N %d\n\n" % len(ccc_runs))

    w("/* full canonical decomposition: {code point, length, d0, d1, d2, d3}, sorted by code point */\n")
    w("static const uint32_t UNI_DECOMP[][6] = {\n")
    for i in range(0, len(decomp), 3):
        w("  " + " ".join(
            "{0x%X,%d,%s}," % (cp, len(d), ",".join("0x%X" % x for x in (d + [0, 0, 0, 0])[:4]))
            for cp, d in decomp[i:i + 3]) + "\n")
    w("};\n#define UNI_DECOMP_N %d\n\n" % len(decomp))

    w("/* canonical composition: {first, second, composite}, sorted by (first, second) */\n")
    w("static const uint32_t UNI_COMPOSE[][3] = {\n")
    for i in range(0, len(compose), 4):
        w("  " + " ".join("{0x%X,0x%X,0x%X}," % c for c in compose[i:i + 4]) + "\n")
    w("};\n#define UNI_COMPOSE_N %d\n\n" % len(compose))
    w("#endif /* UNICODE_TABLES_H */\n")


if __name__ == "__main__":
    main()
